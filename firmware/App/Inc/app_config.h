/**
 * app_config.h - the ONLY place with project-specific settings.
 */
#ifndef APP_CONFIG_H
#define APP_CONFIG_H

/* ---------------- WS2812B ---------------- */
#define WS2812_LED_COUNT        1U            /* number of LEDs in the chain (all show the same colour) */
#define WS2812_TIM_CLK_HZ       170000000UL   /* clock of the timer driving the data line (TIM1 @ 170 MHz) */
#define WS2812_RESET_SLOTS      240U          /* low slots after the data = latch/reset (240 * 1.25us = 300us) */

/* ---------------- LED effects (task 2.1) ---------------- */
#define LED_PERIOD_MS           3000U         /* T = 3 s: period of R (square) and G (sawtooth) */
#define LED_BRIGHTNESS_MAX      255U          /* 0..255 - lower it if the LED is too bright */
#define LED_BLINK_ON_MS         200U          /* B channel: ON time of one blink  */
#define LED_BLINK_OFF_MS        200U          /* B channel: OFF time of one blink */
#define LED_BLINK_COUNT         3U            /* B channel: number of blinks after a button press */
#define LED_UPDATE_INTERVAL_MS  10U           /* LED refresh period (100 Hz) */

/* ---------------- Hardware handles / pins (names generated by CubeMX) ---------------- */
#define APP_UART_HANDLE         hlpuart1      /* ST-LINK virtual COM port on NUCLEO-G474RE */
#define APP_WS2812_TIM_HANDLE   htim1
#define APP_WS2812_TIM_CHANNEL  TIM_CHANNEL_1 /* TIM1_CH1 = PA8 */

#define APP_BTN_PORT            B1_GPIO_Port  /* user button, PC13 */
#define APP_BTN_PIN             B1_Pin
#define APP_BTN_ACTIVE_STATE    GPIO_PIN_SET  /* level read while the button is pressed */
#define APP_BTN_DEBOUNCE_MS     30U

#endif /* APP_CONFIG_H */
